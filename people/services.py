"""Authorized, serialized admission and enrollment writes; history is append-only."""

from datetime import timedelta

from django.core.exceptions import ValidationError
from django.db import transaction
from django.utils import timezone

from academics.models import AcademicYear
from audit.services import record_event
from core.operations import require_capability
from core.uploads import image_write

from .models import AdmissionCounter, Enrollment, GuardianStudent, Student


def lock_year(pk):
    year = AcademicYear.objects.select_for_update().get(pk=pk)
    if year.status != "open":
        raise ValidationError(
            "This academic year is closed or archived; its records are protected."
        )
    return year


def check_identity(data, *, exclude=None):
    students = Student.objects.exclude(pk=exclude) if exclude else Student.objects.all()
    if (
        data.get("external_reference")
        and students.filter(external_reference__iexact=data["external_reference"]).exists()
    ):
        raise ValidationError({"external_reference": "This source reference is already admitted."})
    if (
        data.get("date_of_birth")
        and students.filter(
            first_name__iexact=data["first_name"],
            last_name__iexact=data["last_name"],
            date_of_birth=data["date_of_birth"],
        ).exists()
    ):
        raise ValidationError(
            "Possible duplicate: a student with this name and birth date exists. "
            "Review the existing profile."
        )


def next_admission_number():
    AdmissionCounter.objects.get_or_create(pk=1)
    counter = AdmissionCounter.objects.select_for_update().get(pk=1)
    while Student.objects.filter(admission_number__iexact=f"RW-{counter.next_number:07d}").exists():
        counter.next_number += 1
    number = f"RW-{counter.next_number:07d}"
    counter.next_number += 1
    counter.save(update_fields=["next_number"])
    return number


@transaction.atomic
def admit_student(actor, *, data, academic_year, section, started_on, roll_number="", guardians=()):
    require_capability(actor, "people.add_student", student_scope=True)
    year = lock_year(academic_year.pk)
    allowed = {
        "first_name",
        "last_name",
        "date_of_birth",
        "admission_date",
        "external_reference",
        "photo",
    }
    if set(data) - allowed:
        raise ValidationError("Admission identifiers and status are generated by the school.")
    # Lock the counter before duplicate checks so simultaneous admissions cannot pass each other.
    number = next_admission_number()
    check_identity(data)
    if data["admission_date"] > timezone.localdate():
        raise ValidationError({"admission_date": "Admission date cannot be in the future."})
    if started_on < data["admission_date"]:
        raise ValidationError({"started_on": "Enrollment cannot start before admission."})
    student = Student(admission_number=number, **data)
    student.full_clean()
    with image_write(student, "photo"):
        student.save()
        placement = Enrollment(
            student=student,
            academic_year=year,
            section=section,
            started_on=started_on,
            roll_number=roll_number,
        )
        placement.full_clean()
        placement.save()
        for guardian, relationship in guardians:
            require_capability(actor, "people.add_guardianstudent", student_scope=True)
            link = GuardianStudent(student=student, guardian=guardian, relationship=relationship)
            link.full_clean()
            link.save()
        record_event("student.admitted", actor=actor, target=student.pk)
    return student


@transaction.atomic
def update_student(actor, pk, data):
    require_capability(actor, "people.change_student", student_scope=True)
    student = Student.objects.select_for_update().get(pk=pk)
    allowed = {"first_name", "last_name", "date_of_birth", "photo"}
    if set(data) - allowed:
        raise ValidationError(
            "Admission identifiers, dates and enrollment status cannot be edited here."
        )
    if not student.is_active:
        raise ValidationError(
            "Inactive student profiles are protected. Their admission history is retained."
        )
    check_identity(
        {
            "first_name": data.get("first_name", student.first_name),
            "last_name": data.get("last_name", student.last_name),
            "date_of_birth": data.get("date_of_birth", student.date_of_birth),
        },
        exclude=pk,
    )
    for field, value in data.items():
        setattr(student, field, value)
    student.full_clean()
    with image_write(student, "photo"):
        student.save()
        record_event("student.updated", actor=actor, target=student.pk)
    return student


@transaction.atomic
def correct_roll(actor, pk, *, expected_enrollment, roll_number):
    require_capability(actor, "people.change_student", student_scope=True)
    source = Enrollment.objects.filter(student_id=pk, is_active=True).first()
    if not source:
        raise ValidationError("This student has no active enrollment.")
    lock_year(source.academic_year_id)
    student = Student.objects.select_for_update().get(pk=pk)
    current = Enrollment.objects.select_for_update().filter(student=student, is_active=True).first()
    if not current or current.pk != expected_enrollment or not student.is_active:
        raise ValidationError("The enrollment changed. Reload the student profile.")
    current.roll_number = roll_number
    current.full_clean()
    current.save(update_fields=["roll_number", "updated_at"])
    record_event("enrollment.roll_corrected", actor=actor, target=current.pk)
    return current


@transaction.atomic
def transition_student(
    actor,
    pk,
    *,
    action,
    effective_on,
    expected_enrollment,
    academic_year=None,
    section=None,
    roll_number="",
    notes="",
):
    require_capability(actor, "people.transition_students", student_scope=True)
    if action not in {"transfer", "promote", "withdraw", "graduate", "transfer_out"}:
        raise ValidationError("Choose a supported enrollment action.")
    # All year locks precede student locks, matching admissions and year closure.
    source = Enrollment.objects.filter(student_id=pk, is_active=True).first()
    if not source:
        raise ValidationError("This student has no active enrollment.")
    year_ids = {source.academic_year_id}
    if academic_year:
        year_ids.add(academic_year.pk)
    years = {key: lock_year(key) for key in sorted(year_ids)}
    student = Student.objects.select_for_update().get(pk=pk)
    current = Enrollment.objects.select_for_update().filter(student=student, is_active=True).first()
    if not current or current.pk != expected_enrollment or not student.is_active:
        raise ValidationError("The enrollment changed since this form opened. Reload the profile.")
    if not current.started_on <= effective_on <= current.academic_year.ends_on:
        raise ValidationError({"effective_on": "Choose a date inside the active enrollment."})
    if action in {"transfer", "promote"}:
        if not academic_year or not section:
            raise ValidationError("Choose a destination academic year and section.")
        if action == "transfer" and (
            academic_year.pk != current.academic_year_id or section.pk == current.section_id
        ):
            raise ValidationError(
                "A section transfer must select another section in the same year."
            )
        if action == "promote" and academic_year.starts_on <= current.academic_year.ends_on:
            raise ValidationError("Promotion requires a later, non-overlapping academic year.")
        if (
            action == "promote"
            and section.school_class.sort_order <= current.section.school_class.sort_order
        ):
            raise ValidationError(
                "Promotion requires a higher class. Use section transfer for a same-year move."
            )
    current.ended_on = effective_on
    current.is_active = False
    current.exit_reason = action
    current.notes = notes
    current.full_clean()
    current.save()
    if action in {"transfer", "promote"}:
        start = (
            effective_on + timedelta(days=1) if action == "transfer" else academic_year.starts_on
        )
        destination = Enrollment(
            student=student,
            academic_year=years[academic_year.pk],
            section=section,
            started_on=start,
            roll_number=roll_number,
        )
        destination.full_clean()
        destination.save()
    else:
        student.is_active = False
        student.status = {
            "withdraw": "withdrawn",
            "graduate": "graduated",
            "transfer_out": "transferred",
        }[action]
        student.save(update_fields=["is_active", "status", "updated_at"])
    record_event(f"student.{action}", actor=actor, target=student.pk)
    return student
